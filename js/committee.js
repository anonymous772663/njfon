const leadershipGrid = document.getElementById("leadershipGrid");
const committeeGrid = document.getElementById("committeeGrid");
const honoraryGrid = document.getElementById("honoraryGrid");


// =====================================================
// REUSABLE MEMBER CARD
// =====================================================

function createMemberCard(member, index) {

    return `
        <article class="member-card reveal">

            <div class="member-photo">

                <img
                    src="${member.image}"
                    alt="${member.name}"
                    loading="lazy"
                >

                <div class="member-index">
                    ${String(index + 1).padStart(2, "0")}
                </div>

            </div>

            <div class="member-info">

                <h3>${member.name}</h3>

                <span>${member.role}</span>

                <p>${member.description}</p>

            </div>

        </article>
    `;
}


// =====================================================
// EXECUTIVE MEMBERS
// Numbering: 01, 02, 03...
// =====================================================

function renderLeadership() {

    if (!leadershipGrid) return;

    const leaders = committeeMembers.filter(
        member => member.leader === true
    );

    leadershipGrid.innerHTML = leaders.map(
        (member, index) => `
            <article class="leader-card reveal">

                <div class="leader-image">

                    <img
                        src="${member.image}"
                        alt="${member.name}"
                        loading="lazy"
                    >

                </div>

                <div class="leader-number">
                    ${String(index + 1).padStart(2, "0")}
                </div>

                <div class="leader-info">

                    <span class="leader-role">
                        ${member.role}
                    </span>

                    <h3>${member.name}</h3>

                    <p>${member.description}</p>

                </div>

            </article>
        `
    ).join("");
}


// =====================================================
// HONORARY EXECUTIVE MEMBERS
// Numbering starts again at 01.
// =====================================================

function renderCommittee() {

    if (!committeeGrid) return;

    const members = committeeMembers.filter(
        member => member.sector === "honorary-executive"
    );

    committeeGrid.innerHTML = members.map(
        (member, index) => createMemberCard(member, index)
    ).join("");
}


// =====================================================
// HONORARY MEMBERS
// Numbering starts independently at 01.
// =====================================================

function renderHonoraryMembers() {

    if (!honoraryGrid) return;

    const members = committeeMembers.filter(
        member => member.sector === "honorary"
    );

    honoraryGrid.innerHTML = members.map(
        (member, index) => createMemberCard(member, index)
    ).join("");
}


// =====================================================
// RENDER ALL THREE SECTIONS
// =====================================================

renderLeadership();
renderCommittee();
renderHonoraryMembers();


// =====================================================
// THEME SYSTEM
// =====================================================

const themeButton = document.getElementById("themeButton");
const themePanel = document.getElementById("themePanel");

const themes = [
    "blend",
    "emerald",
    "royal",
    "golden",
    "neon",
    "violet"
];

function applyTheme(theme) {

    themes.forEach(name => {
        document.body.classList.remove("theme-" + name);
    });

    document.body.classList.add("theme-" + theme);

    localStorage.setItem("njfn-theme", theme);
}

applyTheme(
    localStorage.getItem("njfn-theme") || "blend"
);


// =====================================================
// THEME PANEL
// =====================================================

if (themeButton && themePanel) {

    themeButton.addEventListener("click", event => {

        event.stopPropagation();
        themePanel.classList.toggle("open");

    });

    document.querySelectorAll(".theme-option").forEach(option => {

        option.addEventListener("click", () => {

            const selectedTheme = option.dataset.theme;

            if (themes.includes(selectedTheme)) {
                applyTheme(selectedTheme);
            }

            themePanel.classList.remove("open");

        });

    });

    document.addEventListener("click", event => {

        if (
            !event.target.closest(".theme-panel") &&
            !event.target.closest("#themeButton")
        ) {
            themePanel.classList.remove("open");
        }

    });
}


// =====================================================
// LIGHT / DARK MODE
// =====================================================

const modeButton = document.getElementById("modeButton");

function updateModeIcon() {

    if (!modeButton) return;

    const light = document.body.classList.contains("light");

    if (light) {

        modeButton.innerHTML = `
            <svg viewBox="0 0 24 24">
                <circle cx="12" cy="12" r="4"
                    fill="none" stroke="currentColor"
                    stroke-width="1.8"/>
                <path d="M12 2v2M12 20v2M2 12h2M20 12h2"
                    fill="none" stroke="currentColor"
                    stroke-width="1.8" stroke-linecap="round"/>
            </svg>
        `;

    } else {

        modeButton.innerHTML = `
            <svg viewBox="0 0 24 24">
                <path d="M21 12.8A8.5 8.5 0 1 1 11.2 3a6.7 6.7 0 0 0 9.8 9.8Z"
                    fill="none" stroke="currentColor"
                    stroke-width="1.8"/>
            </svg>
        `;

    }
}

if (localStorage.getItem("njfn-mode") === "light") {
    document.body.classList.add("light");
}

updateModeIcon();

if (modeButton) {

    modeButton.addEventListener("click", () => {

        document.body.classList.toggle("light");

        localStorage.setItem(
            "njfn-mode",
            document.body.classList.contains("light") ? "light" : "dark"
        );

        updateModeIcon();

    });
}


