// =========================================================
// EVENT CARD TEMPLATES
// =========================================================

function eventDetailsUrl(event) {
    return `event-details.html?id=${encodeURIComponent(event.id)}`;
}

function safeText(value = "") {
    return String(value)
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;")
        .replaceAll('"', "&quot;")
        .replaceAll("'", "&#039;");
}

function upcomingTemplate(event, index) {
    const highlights = (event.highlights || [])
        .map(item => `<span class="highlight">${safeText(item)}</span>`)
        .join("");

    // Upcoming event details stay text-focused.
    // Keep the card cover as the only image; do not repeat story/gallery photos below.
    const storyText = (event.story || [])
        .map(item => `<p class="upcoming-story-text">${safeText(item.text)}</p>`)
        .join("");

    return `
        <article class="upcoming-card" data-event-id="${safeText(event.id)}">
            <div class="upcoming-main">
                <div class="upcoming-image">
                    <img src="${event.cover}" alt="${safeText(event.title)}" loading="lazy">
                    <span class="event-image-badge">UPCOMING</span>
                </div>

                <div class="upcoming-content">
                    <span class="event-status">UPCOMING EVENT</span>
                    <h3>${safeText(event.title)}</h3>

                    <div class="event-details">
                        <span class="event-detail"><b>DATE</b>📅 ${safeText(event.date)}</span>
                        <span class="event-detail"><b>TIME</b>🕒 ${safeText(event.time)}</span>
                        <span class="event-detail"><b>LOCATION</b>📍 ${safeText(event.address)}</span>
                    </div>

                    <p class="event-description">${safeText(event.shortDescription)}</p>

                    <button class="read-btn upcoming-toggle"
                            type="button"
                            aria-expanded="false"
                            aria-controls="upcoming-more-${index}">
                        VIEW DETAILS
                    </button>
                </div>
            </div>

            <div class="upcoming-more" id="upcoming-more-${index}" aria-hidden="true">
                <div class="more-inner">
                    <div class="more-heading">
                        <span class="small-word">EVENT DETAILS</span>
                        <h4>${safeText(event.title)}</h4>
                    </div>

                    <p>${safeText(event.description)}</p>

                    ${highlights ? `<div class="highlights">${highlights}</div>` : ""}

                    ${storyText ? `
                        <div class="upcoming-story-text-list">
                            ${storyText}
                        </div>
                    ` : ""}

                    <button class="close-details" type="button">CLOSE DETAILS ↑</button>
                </div>
            </div>
        </article>
    `;
}

function pastTemplate(event) {
    return `
        <article class="past-card">
            <a href="${eventDetailsUrl(event)}" class="past-image" aria-label="Read ${safeText(event.title)}">
                <img src="${event.cover}" alt="${safeText(event.title)}" loading="lazy">
                <span class="past-overlay">READ EVENT →</span>
            </a>

            <div class="past-content">
                <span class="past-date">${safeText(event.date)}</span>
                <h3>${safeText(event.title)}</h3>
                <div class="past-meta">
                    <span>🕒 ${safeText(event.time)}</span>
                    <span>📍 ${safeText(event.location)}</span>
                </div>
                <p>${safeText(event.shortDescription)}</p>
                <a href="${eventDetailsUrl(event)}" class="past-read">READ EVENT</a>
            </div>
        </article>
    `;
}

document.addEventListener("DOMContentLoaded", () => {
    const upcoming = document.getElementById("upcomingEvents");
    const past = document.getElementById("pastEvents");

    const parseDate = (value) => new Date(value);

    const sortAscending = (a, b) => parseDate(a.date) - parseDate(b.date);
    const sortDescending = (a, b) => parseDate(b.date) - parseDate(a.date);

    if (upcoming) {
        const allEvents = [
            ...(window.PAST_EVENTS || []),
            ...(window.UPCOMING_EVENTS || [])
        ];
        const items = allEvents
            .filter(event => event.status === "upcoming")
            .sort(sortAscending);

        upcoming.innerHTML = items.length
            ? items.map(upcomingTemplate).join("")
            : `<div class="empty-events">No upcoming events have been announced yet.</div>`;
    }

    if (past) {
        const allEvents = [
            ...(window.PAST_EVENTS || []),
            ...(window.UPCOMING_EVENTS || [])
        ];
        const items = allEvents
            .filter(event => event.status === "past")
            .sort(sortDescending);

        past.innerHTML = items.length
            ? items.map(pastTemplate).join("")
            : `<div class="empty-events">No past events are available yet.</div>`;
    }

    // Upcoming events stay on this page.
    // Open/close their details instead of sending visitors to another page.
    document.querySelectorAll(".upcoming-toggle").forEach(button => {
        button.addEventListener("click", () => {
            const card = button.closest(".upcoming-card");
            const details = card.querySelector(".upcoming-more");
            const isOpen = card.classList.toggle("open");

            button.setAttribute("aria-expanded", String(isOpen));
            details.setAttribute("aria-hidden", String(!isOpen));
            button.textContent = isOpen ? "HIDE DETAILS" : "VIEW DETAILS";

            if (isOpen) {
                setTimeout(() => {
                    details.scrollIntoView({ behavior: "smooth", block: "nearest" });
                }, 80);
            }
        });
    });

    document.querySelectorAll(".close-details").forEach(button => {
        button.addEventListener("click", () => {
            const card = button.closest(".upcoming-card");
            const toggle = card.querySelector(".upcoming-toggle");
            const details = card.querySelector(".upcoming-more");

            card.classList.remove("open");
            toggle.setAttribute("aria-expanded", "false");
            toggle.textContent = "VIEW DETAILS";
            details.setAttribute("aria-hidden", "true");

            card.scrollIntoView({ behavior: "smooth", block: "center" });
        });
    });
});
